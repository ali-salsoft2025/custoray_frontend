export function getInvoiceTemplate(id: InvoiceTemplateId): InvoiceTemplateDefinition {
  return INVOICE_TEMPLATES.find((t) => t.id === id) ?? INVOICE_TEMPLATES[0]
}

export function resolveInvoiceTemplate(
  id: InvoiceTemplateId,
  colorOverrides?: InvoiceTemplateColorOverrides
): InvoiceTemplateDefinition {
  const base = getInvoiceTemplate(id)
  return colorOverrides ? { ...base, ...colorOverrides } : base
}

export function getDefaultColorsForTemplate(
  id: InvoiceTemplateId
): InvoiceTemplateColorOverrides {
  const t = getInvoiceTemplate(id)
  return {
    accent: t.accent,
    accentMuted: t.accentMuted,
    headerBg: t.headerBg,
    headerText: t.headerText,
    tableHeadBg: t.tableHeadBg,
    tableHeadText: t.tableHeadText,
    billToBg: t.billToBg,
    billToBorder: t.billToBorder,
    grandTotalBg: t.grandTotalBg,
    grandTotalText: t.grandTotalText,
  }
}

type StoredTemplateColors = Partial<
  Record<InvoiceTemplateId, InvoiceTemplateColorOverrides>
>

function loadAllTemplateColors(): StoredTemplateColors {
  if (typeof window === "undefined") return {}
  const raw = window.localStorage.getItem(INVOICE_TEMPLATE_COLORS_STORAGE_KEY)
  if (!raw) return {}
  try {
    return JSON.parse(raw) as StoredTemplateColors
  } catch {
    return {}
  }
}

export function loadInvoiceTemplateColors(
  id: InvoiceTemplateId
): InvoiceTemplateColorOverrides {
  const stored = loadAllTemplateColors()[id]
  return stored ? { ...getDefaultColorsForTemplate(id), ...stored } : getDefaultColorsForTemplate(id)
}

export function saveInvoiceTemplateColors(
  id: InvoiceTemplateId,
  colors: InvoiceTemplateColorOverrides
): void {
  if (typeof window === "undefined") return
  const all = loadAllTemplateColors()
  all[id] = colors
  window.localStorage.setItem(INVOICE_TEMPLATE_COLORS_STORAGE_KEY, JSON.stringify(all))
}

export function resetInvoiceTemplateColors(id: InvoiceTemplateId): void {
  if (typeof window === "undefined") return
  const all = loadAllTemplateColors()
  delete all[id]
  window.localStorage.setItem(INVOICE_TEMPLATE_COLORS_STORAGE_KEY, JSON.stringify(all))
}

export function loadInvoiceTemplate(): InvoiceTemplateId {
  if (typeof window === "undefined") return "classic"
  const raw = window.localStorage.getItem(INVOICE_TEMPLATE_STORAGE_KEY)
  if (!raw || raw.startsWith("custom:")) return "classic"
  const parsed = invoiceTemplateIdSchema.safeParse(raw)
  return parsed.success ? parsed.data : "classic"
}

export function saveInvoiceTemplate(id: InvoiceTemplateId): void {
  if (typeof window === "undefined") return
  window.localStorage.setItem(INVOICE_TEMPLATE_STORAGE_KEY, id)
}

