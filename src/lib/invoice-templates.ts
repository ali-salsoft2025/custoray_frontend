const INVOICE_BUILDER_STORAGE_KEY = "custoray-invoice-builder-v1"
const INVOICE_CUSTOM_TEMPLATES_KEY = "custoray-invoice-custom-templates-v1"

export function loadInvoiceBuilderConfig(): InvoiceBuilderConfig {
  if (typeof window === "undefined") return defaultInvoiceBuilderConfig()
  try {
    const raw = window.localStorage.getItem(INVOICE_BUILDER_STORAGE_KEY)
    if (!raw) {
      const legacy = loadInvoiceTemplateCopy()
      return {
        ...defaultInvoiceBuilderConfig(),
        labels: copyToBuilderLabels(legacy),
      }
    }
    const parsed = invoiceBuilderConfigSchema.safeParse(JSON.parse(raw))
    return parsed.success
      ? normalizeInvoiceBuilderConfig(parsed.data)
      : normalizeInvoiceBuilderConfig(JSON.parse(raw) as Partial<InvoiceBuilderConfig>)
  } catch {
    return defaultInvoiceBuilderConfig()
  }
}

export function saveInvoiceBuilderConfig(config: InvoiceBuilderConfig): void {
  if (typeof window === "undefined") return
  window.localStorage.setItem(INVOICE_BUILDER_STORAGE_KEY, JSON.stringify(config))
  saveInvoiceTemplateCopy(builderConfigToCopy(config))
}

export function loadCustomInvoiceTemplates(): CustomInvoiceTemplate[] {
  if (typeof window === "undefined") return []
  try {
    const raw = window.localStorage.getItem(INVOICE_CUSTOM_TEMPLATES_KEY)
    if (!raw) return []
    const parsed = z.array(customInvoiceTemplateSchema).safeParse(JSON.parse(raw))
    if (parsed.success) return parsed.data
    const loose = JSON.parse(raw) as CustomInvoiceTemplate[]
    if (!Array.isArray(loose)) return []
    return loose.map((t) => ({
      ...t,
      builder: normalizeInvoiceBuilderConfig(t.builder),
    }))
  } catch {
    return []
  }
}

export function saveCustomInvoiceTemplates(templates: CustomInvoiceTemplate[]): void {
  if (typeof window === "undefined") return
  window.localStorage.setItem(INVOICE_CUSTOM_TEMPLATES_KEY, JSON.stringify(templates))
}

