export type ActiveInvoiceTemplateRef =
  | { kind: "preset"; id: InvoiceTemplateId }
  | { kind: "custom"; id: string }

export function loadActiveInvoiceTemplateRef(): ActiveInvoiceTemplateRef {
  if (typeof window === "undefined") return { kind: "preset", id: "classic" }
  const raw = window.localStorage.getItem(INVOICE_TEMPLATE_STORAGE_KEY)
  if (raw?.startsWith("custom:")) {
    return { kind: "custom", id: raw.slice("custom:".length) }
  }
  const parsed = invoiceTemplateIdSchema.safeParse(raw)
  return { kind: "preset", id: parsed.success ? parsed.data : "classic" }
}

export function saveActiveInvoiceTemplateRef(ref: ActiveInvoiceTemplateRef): void {
  if (typeof window === "undefined") return
  if (ref.kind === "custom") {
    window.localStorage.setItem(INVOICE_TEMPLATE_STORAGE_KEY, `custom:${ref.id}`)
  } else {
    window.localStorage.setItem(INVOICE_TEMPLATE_STORAGE_KEY, ref.id)
  }
}

export function resolveActiveTemplateForPdf(): {
  templateId: InvoiceTemplateId
  colors: InvoiceTemplateColorOverrides
  builder: InvoiceBuilderConfig
} {
  const ref = loadActiveInvoiceTemplateRef()
  if (ref.kind === "custom") {
    const custom = loadCustomInvoiceTemplates().find((t) => t.id === ref.id)
    if (custom) {
      return {
        templateId: custom.baseLayout,
        colors: custom.colors,
        builder: custom.builder,
      }
    }
  }
  const presetId = ref.kind === "preset" ? ref.id : "classic"
  const preset = resolvePresetTemplate(presetId)
  return {
    templateId: presetId,
    colors: preset.colors,
    builder: preset.builder,
  }
}

